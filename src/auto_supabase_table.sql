
CREATE TYPE public.sex AS ENUM ('Mr', 'Mme');

CREATE TYPE public.employer_rule AS ENUM (
    'cleaner', 'receptionnist', 'security', 'cooker'
);

CREATE TYPE public.bedroom_option AS ENUM ('VENT', 'CLIM');

CREATE TYPE public.bedroom_stage_id AS ENUM (
    'REZ de chaussée',
    'Étage 1',
    'Étage 2',
    'Étage 3',
    'Étage 4',
    'Étage 5'
);

CREATE TYPE public.customer_status AS ENUM (
    'CHECK_IN', 'CHECK_UPDATE', 'CHECK_MOVE', 'CHECK_OUT'
);







CREATE TABLE public.employer_table (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sexe public.sex NOT NULL,
    name text NOT NULL,
    rules public.employer_rule[] NOT NULL DEFAULT '{}'
);

CREATE TABLE public.bedroom_ctg_table (
    id text PRIMARY KEY,
    name text NOT NULL,
    price integer NOT NULL CHECK (price >= 0),
    option public.bedroom_option NOT NULL
);

CREATE TABLE public.bedroom_table (
    id text PRIMARY KEY,
    name text NOT NULL,
    stage public.bedroom_stage_id NOT NULL,
    issue text
);






CREATE TABLE public.cleaning_book (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id text NOT NULL REFERENCES public.bedroom_table(id),
    auth_session bigint NOT NULL REFERENCES public.employer_table(id),
    date timestamptz NOT NULL DEFAULT now(),
    description text,
    cancel_date timestamptz,
    cancel_by bigint REFERENCES public.employer_table(id),

    valet_id bigint NOT NULL REFERENCES public.employer_table(id),
    done timestamptz NOT NULL
);

CREATE TABLE public.customer_book (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id text NOT NULL REFERENCES public.bedroom_table(id),
    auth_session bigint NOT NULL REFERENCES public.employer_table(id),
    date timestamptz NOT NULL DEFAULT now(),
    description text,
    cancel_date timestamptz,
    cancel_by bigint REFERENCES public.employer_table(id),

    customer_id bigint NOT NULL REFERENCES public.customer_book(id),
    actions jsonb NOT NULL DEFAULT '[]'::jsonb
);



CREATE TABLE public.reservation_book (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id text NOT NULL REFERENCES public.bedroom_table(id),
    auth_session bigint NOT NULL REFERENCES public.employer_table(id),
    date timestamptz NOT NULL DEFAULT now(),
    description text,
    cancel_date timestamptz,
    cancel_by bigint REFERENCES public.employer_table(id),

    name text NOT NULL,
    start_date timestamptz NOT NULL,
    end_date timestamptz NOT NULL,
    CHECK (end_date > start_date)
);

CREATE TABLE public.restaurant_book (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id text NOT NULL REFERENCES public.bedroom_table(id),
    auth_session bigint NOT NULL REFERENCES public.employer_table(id),
    date timestamptz NOT NULL DEFAULT now(),
    description text,
    cancel_date timestamptz,
    cancel_by bigint REFERENCES public.employer_table(id),

    customer_id bigint NOT NULL REFERENCES public.customer_book(id),
    article text NOT NULL,
    price integer NOT NULL CHECK (price >= 0),
    paid boolean NOT NULL DEFAULT false
);






